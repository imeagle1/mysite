import fs from 'node:fs';
import path from 'node:path';

const fontsDir = path.join(process.cwd(), 'public', 'fonts');
const cssOutPath = path.join(fontsDir, 'custom-font.css');

const FORMAT_MAP = {
  '.woff2': 'woff2',
  '.woff': 'woff',
  '.ttf': 'truetype',
  '.otf': 'opentype',
};

const FORMAT_PRIORITY = ['.woff2', '.woff', '.ttf', '.otf'];

function isVariableFont(baseName) {
  return /(vf$|vf[-_.]|[-_]vf|variable)/i.test(baseName);
}

function detectWeight(baseName, index) {
  if (isVariableFont(baseName)) return '100 900';
  const lower = baseName.toLowerCase();
  if (/(extralight|ultralight|extra-light|ultra-light|200)/.test(lower)) return '200';
  if (/(thin|100)/.test(lower)) return '100';
  if (/(light|300)/.test(lower)) return '300';
  if (/(semibold|demibold|semi-bold|demi-bold|600)/.test(lower)) return '600';
  if (/(extrabold|ultrabold|extra-bold|ultra-bold|heavy|800)/.test(lower)) return '800';
  if (/(black|900)/.test(lower)) return '900';
  if (/(bold|700)/.test(lower)) return '700';
  if (/(medium|500)/.test(lower)) return '500';
  if (/(regular|normal|book|400)/.test(lower)) return '400';

  const fallbackWeights = ['400', '500', '700', '600', '300', '800'];
  return fallbackWeights[index] || '400';
}

function detectFamilyAlias(baseNames) {
  if (!baseNames.length) return '';
  const cleaned = baseNames[0]
    .replace(/[-_ ]?(variable|thin|extralight|ultralight|light|regular|normal|medium|semibold|demibold|bold|extrabold|ultrabold|heavy|black|\d{3})$/i, '')
    .trim();
  return cleaned.replace(/[^a-zA-Z0-9_-]/g, '');
}

if (!fs.existsSync(fontsDir)) {
  process.exit(0);
}

const fontFiles = fs
  .readdirSync(fontsDir)
  .filter((name) => {
    const ext = path.extname(name).toLowerCase();
    return Object.prototype.hasOwnProperty.call(FORMAT_MAP, ext);
  })
  .sort((a, b) => a.localeCompare(b));

if (fontFiles.length === 0) {
  console.log('[fonts] No .woff2/.woff/.ttf/.otf files found locally; keeping configured custom-font.css');
  process.exit(0);
}

// Group multi-format files sharing the same base name (e.g. IRANYekanXVF.woff2 + .woff + .ttf)
const grouped = new Map();
for (const file of fontFiles) {
  const ext = path.extname(file).toLowerCase();
  const base = path.basename(file, path.extname(file));
  if (!grouped.has(base)) {
    grouped.set(base, []);
  }
  grouped.get(base).push({ file, ext });
}

for (const list of grouped.values()) {
  list.sort((a, b) => FORMAT_PRIORITY.indexOf(a.ext) - FORMAT_PRIORITY.indexOf(b.ext));
}

const baseNames = Array.from(grouped.keys());
const detectedAlias = detectFamilyAlias(baseNames);
const familiesToRegister = [];
if (detectedAlias) {
  familiesToRegister.push(detectedAlias);
}
if (!familiesToRegister.some((f) => f.toLowerCase() === 'iramocustomfont')) {
  familiesToRegister.push('IramoCustomFont');
}

const blocks = [
  '/*',
  ' * Auto-generated by scripts/generate-custom-font-css.mjs',
  ` * Detected ${fontFiles.length} font asset(s) grouped into ${baseNames.length} font face(s)`,
  ' */',
  '',
];

for (const familyName of familiesToRegister) {
  baseNames.forEach((base, idx) => {
    const filesForBase = grouped.get(base) || [];
    const weight = detectWeight(base, idx);
    const srcParts = filesForBase.map(
      ({ file, ext }) => `url('./${file}') format('${FORMAT_MAP[ext]}')`
    );
    blocks.push(
      '@font-face {',
      `  font-family: '${familyName}';`,
      `  src: ${srcParts.join(',\n       ')};`,
      `  font-weight: ${weight};`,
      '  font-style: normal;',
      '  font-display: swap;',
      '}',
      ''
    );
  });
}

fs.writeFileSync(cssOutPath, blocks.join('\n'), 'utf8');
console.log(
  `[fonts] Generated public/fonts/custom-font.css for ${baseNames.join(', ')} (families: ${familiesToRegister.join(', ')})`
);
